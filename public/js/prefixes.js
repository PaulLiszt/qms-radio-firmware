// 呼号 → { prefix, country, code } 或 null（flag 由 flags.js flagImg(code) 渲染）
// 业余无线电呼号前缀形态多样：两字母(BA/DL)、单字母(W/G)、数字+字母(4X/3W/9V)、字母+数字(S2/S5)。
// 按可能性依次尝试，返回首个命中。
export function lookupCallsign(cs) {
  if (!cs) return null;
  const up = String(cs).toUpperCase().replace(/[^A-Z0-9]/g, '');
  const cands = [];
  const dm = up.match(/^(\d)([A-Z])/);   // 4X, 3W, 9V, 5N ...
  const lm2 = up.match(/^([A-Z]{2})/);   // BA, DL, VK ...
  const ld = up.match(/^([A-Z])(\d)/);   // S2, S5, W1(回退用) ...
  const l1 = up.match(/^([A-Z])/);       // W, G, S ...
  if (dm) cands.push(dm[1] + dm[2]);
  if (lm2) cands.push(lm2[1]);
  if (ld) cands.push(ld[1] + ld[2]);
  if (l1) cands.push(l1[1]);
  for (const p of cands) {
    const hit = COUNTRY_BY_PREFIX[p];
    if (hit) return { prefix: p, country: hit[0], code: hit[1] };
  }
  return null;
}
